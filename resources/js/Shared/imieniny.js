/**
 * Zwraca imiona obchodzone w dniu podanym jako Date (domyslnie dzis).
 * Zwraca tablice imion (moze byc pusta jesli data nietypowa).
 */
export function imieninyDnia(date = new Date()) {
  const mm = String(date.getMonth() + 1).padStart(2, '0')
  const dd = String(date.getDate()).padStart(2, '0')
  return IMIENINY[`${mm}-${dd}`] || []
}

